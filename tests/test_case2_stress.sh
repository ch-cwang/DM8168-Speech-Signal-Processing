#!/bin/sh
# ==============================================================================
# 测试用例 2: CPU 极端高负载抗撕裂测试
# ==============================================================================

# 确保在编译输出目录下运行
if [ ! -f "./run.sh" ]; then
    echo "错误：找不到可执行脚本 ./run.sh。请在 install 部署目录下运行本脚本。"
    exit 1
fi

echo "======================================================"
echo " [用例 2] CPU 极端高负载抗撕裂测试 (运行 10 秒) "
echo "======================================================"
echo "请先开启旁路抓包 (setup_alsa_snoop.sh on)，并从外部持续输入正弦波。"

# 启动 2 个死循环后台进程，100% 榨干 ARM 端 CPU (纯逻辑死循环，没有任何 IO 阻塞，是最狠的 CPU 杀手)
while true; do :; done &
LOAD_PID1=$!
while true; do :; done &
LOAD_PID2=$!

echo "负载已施加。测试结束后，请将当前目录下的 ./dsp_playback.raw 拷贝至电脑进行检视..."
(sleep 10; echo "") | ./run.sh
RET_VAL=$?

# 清理高负载进程
kill -9 $LOAD_PID1 $LOAD_PID2 2>/dev/null
echo "已清理负载进程。"

if [ $RET_VAL -eq 0 ]; then
    echo "[PASSED] 用例 2 通过：高压下音频内核能稳固处理，无崩溃退出。"
else
    echo "[FAILED] 用例 2 失败：在高压环境下系统崩溃，返回值 $RET_VAL。"
    exit 1
fi
