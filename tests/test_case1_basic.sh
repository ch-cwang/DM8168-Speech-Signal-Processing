#!/bin/sh
# ==============================================================================
# 测试用例 1: 基础音频连通性测试
# ==============================================================================

# 确保在编译输出目录下运行
if [ ! -f "./run.sh" ]; then
    echo "错误：找不到可执行脚本 ./run.sh。请在 install 部署目录下运行本脚本。"
    exit 1
fi

echo "======================================================"
echo " [用例 1] 基础音频连通性测试 (运行 5 秒) "
echo "======================================================"
echo "请先运行 ./tests/setup_alsa_snoop.sh on 开启底层抓包。"
echo "然后用任意单根音频线从播放源输入 1kHz 正弦波至 Line In。"

# 使用括号和 sleep，在 5 秒后通过管道向 ./run.sh (及其启动的 app_host) 输送一个回车符 (Enter) 触发优雅退出
(sleep 5; echo "") | ./run.sh
RET_VAL=$?

if [ $RET_VAL -eq 0 ]; then
    echo "[PASSED] 用例 1 通过：双核握手与音频流转正常，并成功优雅退出。"
else
    echo "[FAILED] 用例 1 失败：进程异常退出，返回值 $RET_VAL。"
    exit 1
fi
