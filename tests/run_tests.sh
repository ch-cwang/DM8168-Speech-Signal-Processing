#!/bin/sh
# ==============================================================================
# DM8168 异构多核音频流控系统 - 自动化测试脚本
# ==============================================================================

# 确保在编译输出目录下运行
if [ ! -f "./app" ]; then
    echo "错误：找不到可执行文件 ./app。请在 install 部署目录下运行本脚本。"
    exit 1
fi

echo "======================================================"
echo " 开始 DM8168 音频核心测试流 "
echo "======================================================"

# ==============================================================================
echo -e "\n[用例 1] 基础音频连通性测试 (运行 5 秒)"
echo "------------------------------------------------------"
echo "请确保已经连接音频对录线，或者环境有背景声音输入。"
# 使用括号和 sleep，在 5 秒后通过管道向 ./app 输送一个回车符 (Enter) 触发优雅退出
(sleep 5; echo "") | ./app
RET_VAL=$?
if [ $RET_VAL -eq 0 ]; then
    echo "[PASSED] 用例 1 通过：双核握手与音频流转正常，并成功优雅退出。"
else
    echo "[FAILED] 用例 1 失败：进程异常退出，返回值 $RET_VAL。"
    exit 1
fi


# ==============================================================================
echo -e "\n[用例 2] CPU 极端高负载抗撕裂测试 (运行 10 秒)"
echo "------------------------------------------------------"
echo "正在创建极限 CPU 负载进程 (dd /dev/urandom)..."

# 启动 2 个高强度无意义计算后台进程，榨干 ARM 端 CPU
dd if=/dev/urandom of=/dev/null bs=1M 2>/dev/null &
LOAD_PID1=$!
dd if=/dev/urandom of=/dev/null bs=1M 2>/dev/null &
LOAD_PID2=$!

echo "负载已施加。启动音频程序，请留意声音是否有严重的撕裂和乱序..."
(sleep 10; echo "") | ./app
RET_VAL=$?

# 清理高负载进程
kill -9 $LOAD_PID1 $LOAD_PID2 2>/dev/null
echo "已清理负载进程。"

if [ $RET_VAL -eq 0 ]; then
    echo "[PASSED] 用例 2 通过：高压下音频内核能稳固处理，无崩溃退出。"
else
    echo "[FAILED] 用例 2 失败：在高压环境下系统崩溃，返回值 $RET_VAL。"
    exit 1
fi


# ==============================================================================
echo -e "\n[用例 3] 频繁启停压力测试 (连续启停 10 次，防僵尸进程与死锁验证)"
echo "------------------------------------------------------"
echo "即将连续启动并瞬间关闭系统，考验 IPC 回收与 ALSA 底层复位能力。"

FAIL_COUNT=0
for i in $(seq 1 10); do
    echo -n "  -> 第 $i 次尝试运行... "
    # 仅运行 1 秒即发起注销攻击
    (sleep 1; echo "") | ./app > /dev/null 2>&1
    RET_VAL=$?
    
    if [ $RET_VAL -eq 0 ]; then
        echo "OK"
    else
        echo "失败 (返回值: $RET_VAL)"
        FAIL_COUNT=$((FAIL_COUNT+1))
    fi
    # 间隔 0.5s 防止串口打印拥堵
    sleep 0.5
done

if [ $FAIL_COUNT -eq 0 ]; then
    echo "[PASSED] 用例 3 通过：完成 10 次极速启停，未发生内存泄漏或进程卡死。"
else
    echo "[FAILED] 用例 3 失败：在第 $FAIL_COUNT 次发生异常！"
    exit 1
fi

echo "======================================================"
echo " 恭喜，所有基础自动化测试用例均已完成！"
echo "======================================================"
