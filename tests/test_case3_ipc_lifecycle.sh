#!/bin/sh
# ==============================================================================
# 测试用例 3: 频繁启停压力测试 (防僵尸进程与死锁验证)
# ==============================================================================

# 确保在编译输出目录下运行
if [ ! -f "./run.sh" ]; then
    echo "错误：找不到可执行脚本 ./run.sh。请在 install 部署目录下运行本脚本。"
    exit 1
fi

echo "======================================================"
echo " [用例 3] 频繁启停压力测试 (连续启停 10 次) "
echo "======================================================"
echo "即将连续启动并瞬间关闭系统，考验 IPC 回收与 ALSA 底层复位能力。"

FAIL_COUNT=0
for i in $(seq 1 10); do
    echo -n "  -> 第 $i 次尝试运行... "
    # 仅运行 1 秒即发起注销攻击
    (sleep 1; echo "") | ./run.sh > /dev/null 2>&1
    RET_VAL=$?
    
    if [ $RET_VAL -eq 0 ]; then
        echo "OK"
    else
        echo "失败 (返回值: $RET_VAL)"
        FAIL_COUNT=$((FAIL_COUNT+1))
    fi
    # 间隔 0.5s 防止串口打印拥堵
    sleep 0.5
done

if [ $FAIL_COUNT -eq 0 ]; then
    echo "[PASSED] 用例 3 通过：完成 10 次极速启停，未发生内存泄漏或进程卡死。"
else
    echo "[FAILED] 用例 3 失败：在第 $FAIL_COUNT 次发生异常！"
    exit 1
fi
